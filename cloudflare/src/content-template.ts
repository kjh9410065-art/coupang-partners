const DISCLOSURE = "이 포스팅은 쿠팡 파트너스 활동의 일환으로, 이에 따른 일정액의 수수료를 제공받습니다.";

/**
 * 쿠팡 상품명을 바탕으로 네이버 블로그용 글을 작성합니다.
 * 가격/배송/검색순위는 넣지 않고, 확인된 상품 특징과 활용 중심으로 구성합니다.
 */
export function buildProductPost(keyword: string, productName: string, researchEvidence: string[] = []) {
  // 상품명에서 실제로 확인되는 특징만 사용합니다.
  const rules: Array<[RegExp, string, string]> = [
    [/무선/, "무선", "무선 방식의 제품으로 상품명에 표시되어 있습니다."],
    [/청소기/, "청소기", "청소 용도의 제품으로 확인됩니다."],
    [/헤드브러시/, "헤드브러시", "헤드브러시가 상품명에 포함되어 있습니다."],
    [/침구브러시/, "침구 브러시", "침구 브러시가 상품명에 포함되어 있어 침구 청소 용도로 살펴볼 수 있습니다."],
    [/필터/, "필터", "필터가 상품명에 포함되어 있습니다."],
    [/LED/, "LED", "LED 조명이 상품명에 표시되어 있습니다."],
    [/링라이트/, "링라이트", "링라이트가 상품명에 표시되어 있어 촬영 조명 용도로 소개되고 있습니다."],
    [/조명/, "조명", "조명 제품으로 표시되어 있습니다."],
    [/촬영/, "촬영", "촬영 용도가 상품명에 직접 표시되어 있습니다."],
    [/핸드폰|스마트폰/, "핸드폰 촬영", "핸드폰을 활용한 촬영과 관련된 제품으로 확인됩니다."],
    [/거치대|거치/, "거치", "기기를 고정해 사용하는 거치 관련 특징이 표시되어 있습니다."],
    [/높이조절|높이/, "높이 조절", "높이 조절이라는 특징이 상품명에 표시되어 있습니다."],
    [/수직촬영/, "수직 촬영", "수직 촬영 용도가 상품명에 표시되어 있습니다."],
    [/유튜브/, "유튜브 촬영", "유튜브 촬영과 관련된 용도가 상품명에 표시되어 있습니다."],
    [/캠핑/, "캠핑", "캠핑 관련 활용처가 상품명에 표시되어 있습니다."],
    [/보온/, "보온", "보온 용도가 상품명에 표시되어 있습니다."],
    [/방한/, "방한", "방한 용도가 상품명에 표시되어 있습니다."],
    [/등산/, "등산", "등산 관련 활용처가 상품명에 표시되어 있습니다."],
    [/러닝/, "러닝", "러닝 관련 활용처가 상품명에 표시되어 있습니다."],
    [/마라톤/, "마라톤", "마라톤 관련 활용처가 상품명에 표시되어 있습니다."],
    [/차량용/, "차량용", "차량에서 사용하는 용도가 상품명에 표시되어 있습니다."],
    [/주방/, "주방용", "주방에서 사용하는 용도로 표시되어 있습니다."],
    [/수납/, "수납", "수납과 관련된 용도가 상품명에 표시되어 있습니다."],
    [/이어폰/, "이어폰", "이어폰 제품으로 확인됩니다."],
    [/공기청정기/, "공기청정기", "공기청정 용도의 제품으로 확인됩니다."],
    [/키보드/, "키보드", "키보드 제품으로 확인됩니다."],
    [/마우스/, "마우스", "마우스 제품으로 확인됩니다."],
  ];

  const matched = rules.filter(([pattern]) => pattern.test(productName));
  const features = [...new Set(matched.map(([, label]) => label))];
  const descriptions = [...new Set(matched.map(([, , description]) => description))];
  const featureText = features.length ? features.join(", ") : productName;

  // 조사 결과는 제품 특징을 보조하는 경우에만 사용합니다. 실제 구매자 후기처럼 쓰지 않습니다.
  const usefulEvidence = researchEvidence
    .map((item) => item.replace(/\s+/g, " ").trim())
    .filter((item) => item.length >= 20 && item.length <= 300)
    .filter((item) => /특징|구성|용도|사용|거치|촬영|청소|필터|조명|무선|브러시/i.test(item))
    .slice(0, 1);

  const titles = [
    `${productName} 특징과 활용법 알아보기`,
    `${productName} 제품 소개와 추천 사용처`,
    `${productName} 어떤 용도로 사용하면 좋을까`,
    `${productName} 장점과 활용 포인트 정리`,
    `${keyword} 찾는다면 살펴볼 ${productName}`,
  ];

  const introduction = descriptions.length
    ? `${productName}은 ${featureText} 등의 특징이 상품명에 표시된 제품입니다. ${descriptions.slice(0, 4).join(" ")}`
    : `${productName}은 ${keyword}와 관련해 살펴볼 수 있는 제품입니다. 상품명에서 확인되는 특징을 중심으로 소개해보겠습니다.`;

  const recommendation = features.length
    ? `${featureText}처럼 필요한 용도와 연결되는 특징이 상품명에 들어가 있어 관련 제품을 찾는 분들이 비교해보기 좋습니다. 특히 원하는 사용 목적이 분명하다면 비슷한 상품 사이에서 필요한 특징을 빠르게 살펴볼 수 있습니다.`
    : `${keyword}와 관련된 제품을 찾고 있다면 먼저 사용할 목적을 정한 뒤 상품명에 표시된 특징과 비교해보는 방법이 좋습니다.`;

  const advantages = features.length
    ? `${featureText}와 같은 핵심 특징을 상품명에서 바로 확인할 수 있다는 점이 장점입니다. 어떤 용도의 제품인지 파악하기 쉽고, 비슷한 상품을 비교할 때도 필요한 기준을 잡기 편합니다.`
    : `상품명과 사용 목적을 기준으로 필요한 제품인지 빠르게 비교할 수 있다는 점이 장점입니다.`;

  const disadvantages = features.length
    ? `상품명에 표시된 특징은 한눈에 확인할 수 있지만 세부적인 기능이나 구성까지 모두 보여주지는 않습니다. 그래서 ${featureText}와 관련해 본인에게 꼭 필요한 부분은 상품 상세 설명에서 확인하는 것이 좋습니다.`
    : `상품명만으로 세부 기능과 구성을 모두 알 수 없다는 점은 아쉬운 부분입니다.`;

  const goodPlace = (() => {
    if (features.some((x) => /촬영|링라이트|핸드폰 촬영|거치|높이 조절|수직 촬영|유튜브/.test(x))) {
      return "책상이나 홈스튜디오처럼 촬영 장비를 설치하는 공간에서 활용하기 좋습니다. 영상이나 사진을 촬영하는 환경이라면 상품명에 표시된 촬영, 조명, 거치 관련 특징을 기준으로 살펴볼 수 있습니다.";
    }
    if (features.some((x) => /청소기|헤드브러시|침구 브러시|필터/.test(x))) {
      return "집 안에서 청소가 필요한 공간을 중심으로 활용하기 좋습니다. 평소 자주 청소하는 공간과 상품명에 표시된 청소 관련 특징을 함께 비교해보면 됩니다.";
    }
    if (features.some((x) => /캠핑|보온|방한|등산|러닝|마라톤/.test(x))) {
      return "상품명에 표시된 야외활동이나 계절 관련 용도가 필요한 상황에서 활용하기 좋습니다. 실제로 필요한 활동과 제품의 표시된 용도를 맞춰보면 됩니다.";
    }
    if (features.includes("차량용")) {
      return "차량 안에서 해당 용도의 제품이 필요한 경우 활용처를 생각해볼 수 있습니다. 평소 차량에서 어떤 상황에 사용할지 먼저 정해보면 좋습니다.";
    }
    return `${keyword}와 관련된 제품이 필요한 공간에서 활용할 수 있습니다. 집이나 작업 공간 등 실제 사용 장소를 먼저 생각하고 제품의 특징과 맞춰보면 좋습니다.`;
  })();

  const recommendedUse = (() => {
    if (features.includes("유튜브 촬영") || features.includes("수직 촬영")) {
      return "유튜브 영상이나 세로형 콘텐츠를 촬영하는 환경에서 추천해볼 만합니다. 핸드폰 촬영이 필요하다면 거치와 촬영 관련 특징을 중심으로 비교해보세요.";
    }
    if (features.includes("청소기")) {
      return "일상적인 집안 청소를 위한 제품을 찾을 때 살펴보기 좋습니다. 헤드브러시나 침구 브러시처럼 상품명에 표시된 구성도 함께 확인해보세요.";
    }
    if (features.some((x) => /캠핑|등산|러닝|마라톤/.test(x))) {
      return "캠핑, 등산, 러닝, 마라톤처럼 상품명에 표시된 활동을 준비할 때 활용처를 생각해볼 수 있습니다.";
    }
    return `${keyword}와 관련된 제품이 필요한 상황에서 활용처를 생각해볼 수 있습니다. 실제 사용할 장소와 목적을 먼저 정해두면 선택하기 편합니다.`;
  })();

  const evidenceNote = usefulEvidence.length
    ? " 관련 공개 자료도 참고했으며, 확인되지 않은 기능이나 성능은 글에 추가하지 않았습니다."
    : "";

  // 요청한 순서대로 구성하고, 가격·배송·검색순위는 포함하지 않습니다.
  const body = [
    "인사말",
    `안녕하세요. 오늘은 ${keyword}를 찾다가 살펴볼 만한 ${productName}을 소개해드릴게요. 제품의 특징과 활용하기 좋은 상황을 중심으로 편하게 정리해보겠습니다.`,
    "제품소개",
    `${introduction}${evidenceNote}`,
    "추천이유",
    recommendation,
    "장점",
    advantages,
    "단점",
    disadvantages,
    "어디에 사용하면 좋은지",
    goodPlace,
    "추천사용처",
    recommendedUse,
    "파트너스 링크",
    "관심이 있다면 아래 상품 확인하기 버튼에서 자세한 상품 정보를 확인해보세요.",
    "마무리 인사",
    `오늘은 ${productName}의 특징과 활용 방법을 중심으로 살펴봤습니다. 필요한 용도와 잘 맞는지 비교해보시고, 세부적인 기능이나 구성은 상품 상세 페이지에서 확인해보시면 좋겠습니다. 읽어주셔서 감사합니다.`,
  ].join("\n\n");

  return { titles, selectedTitle: titles[0], body, disclosure: DISCLOSURE };
}
