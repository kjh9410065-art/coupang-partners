const DISCLOSURE = "이 포스팅은 쿠팡 파트너스 활동의 일환으로, 이에 따른 일정액의 수수료를 제공받습니다.";

/**
 * 상품 소개 글을 사람이 읽는 블로그 글처럼 구성합니다.
 * 가격/배송/검색순위는 사용하지 않으며, 상품명에서 확인되는 특징을 중심으로 작성합니다.
 */
export function buildProductPost(keyword: string, productName: string, _researchEvidence: string[] = []) {
  // 상품명에서 실제로 드러나는 핵심 특징만 골라냅니다.
  // 이 목록에 없는 성능이나 수치는 임의로 만들지 않습니다.
  const tokens = productName.split(/\s+/).filter(Boolean);
  const featurePatterns: Array<[RegExp, string]> = [
    [/무선/, "무선 방식"],
    [/청소기/, "청소기 형태"],
    [/헤드브러시/, "헤드브러시"],
    [/침구브러시/, "침구 브러시"],
    [/필터/, "필터"],
    [/LED/, "LED 조명"],
    [/링라이트/, "링라이트"],
    [/조명/, "촬영 조명"],
    [/촬영/, "촬영 용도"],
    [/핸드폰/, "핸드폰 거치"],
    [/거치대|거치/, "거치 기능"],
    [/높이조절|높이/, "높이 조절"],
    [/수직촬영/, "수직 촬영"],
    [/유튜브/, "유튜브 촬영"],
    [/캠핑/, "캠핑 활용"],
    [/보온/, "보온 용도"],
    [/방한/, "방한 용도"],
    [/등산/, "등산 활용"],
    [/러닝/, "러닝 활용"],
    [/마라톤/, "마라톤 활용"],
    [/차량용/, "차량용"],
    [/주방/, "주방용"],
    [/수납/, "수납 용도"],
    [/이어폰/, "무선 이어폰"],
    [/공기청정기/, "공기청정기"],
  ];

  const features = [...new Set(
    featurePatterns
      .filter(([pattern]) => pattern.test(productName))
      .map(([, label]) => label),
  )];

  // 인식된 특징이 없을 때도 상품명 자체를 중심으로 자연스럽게 소개합니다.
  const featureText = features.length ? features.join(", ") : productName;
  const firstFeatures = features.slice(0, 3);

  const titles = [
    `${productName} 특징과 활용법 알아보기`,
    `${productName} 제품 소개와 추천 사용처`,
    `${productName} 어떤 점이 좋은지 살펴보기`,
    `${productName} 장점과 활용하기 좋은 곳`,
    `${keyword} 찾는다면 살펴볼 ${productName}`,
  ];

  const intro = firstFeatures.length
    ? `${productName}은 ${firstFeatures.join(", ")} 등의 특징이 상품명에 함께 표시된 제품입니다. 이름에 적힌 내용을 보면 어떤 용도로 살펴볼 만한 제품인지 방향을 잡기 좋습니다. 특히 여러 특징이 함께 표시되어 있어 필요한 용도와 맞는지 비교해보기 좋습니다.`
    : `${productName}은 현재 ${keyword} 검색 결과에서 확인된 제품입니다. 상품명에 표시된 내용을 중심으로 어떤 용도로 살펴볼 만한지 자연스럽게 정리해보겠습니다.`;

  const reason = firstFeatures.length
    ? `${firstFeatures.join(", ")}처럼 원하는 용도와 관련된 표현이 상품명에 분명하게 들어가 있다는 점에서 관련 제품을 찾는 분들이 살펴보기 좋습니다. 내가 필요한 사용 목적을 먼저 정해두면 비슷한 상품과 비교할 때도 특징을 빠르게 확인할 수 있습니다.`
    : `제품을 고를 때는 내가 어떤 용도로 사용할지를 먼저 정해두는 것이 좋습니다. 이 제품 역시 상품명에 표시된 특징과 본인의 사용 목적이 잘 맞는지 비교해보면 선택하기 편합니다.`;

  const advantages = features.includes("무선 방식") && features.includes("청소기 형태")
    ? `무선청소기라는 형태에 더해 ${firstFeatures.filter((x) => ["헤드브러시", "침구 브러시", "필터"].includes(x)).join(", ") || "관련 구성"}이 상품명에 함께 표시되어 있어 청소 용도에 맞춰 살펴보기 좋습니다. 필요한 청소 환경과 구성에 맞는지 비교하기에도 편한 편입니다.`
    : firstFeatures.length
      ? `${firstFeatures.join(", ")}와 같은 특징이 상품명에 명확하게 표시되어 있다는 점이 눈에 띕니다. 원하는 용도가 분명하다면 비슷한 제품을 비교할 때 필요한 조건을 빠르게 확인할 수 있습니다.`
      : `상품명에서 확인되는 정보가 비교적 명확해 필요한 용도와 맞는지 살펴보기 편합니다.`;

  const disadvantages = features.length
    ? `반면 상품명에 표시된 특징만으로는 실제 사용 환경에서의 세부적인 편의성이나 구성까지 판단하기 어렵습니다. 그래서 본인에게 중요한 부분은 상품 상세 설명에서 한 번 더 확인하는 것이 좋습니다.`
    : `상품명만으로 확인할 수 있는 정보에는 한계가 있으므로 세부 기능이나 구성은 상품 상세 설명을 함께 확인하는 것이 좋습니다.`;

  const goodPlace = (() => {
    if (features.some((x) => /촬영|링라이트|핸드폰 거치|거치 기능|수직 촬영|유튜브/.test(x))) {
      return `촬영이나 영상 제작처럼 조명과 거치가 필요한 공간에서 활용하기 좋은 제품으로 살펴볼 수 있습니다. 책상이나 촬영 공간처럼 제품을 설치해두고 사용하는 상황과 잘 맞는지 비교해보세요.`;
    }
    if (features.some((x) => /청소기|헤드브러시|침구 브러시|필터/.test(x))) {
      return `집 안에서 청소가 필요한 공간을 중심으로 활용하기 좋습니다. 바닥이나 침구처럼 평소 자주 관리하는 공간을 생각해보고 상품명에 표시된 구성과 사용 목적이 맞는지 살펴보면 됩니다.`;
    }
    if (features.some((x) => /캠핑|보온|방한|등산|러닝|마라톤/.test(x))) {
      return `야외활동을 준비하는 상황에서 활용하기 좋은 제품으로 볼 수 있습니다. 캠핑이나 운동, 야외 활동처럼 상품명에 표시된 용도와 실제 사용 목적이 맞는지 비교해보면 좋습니다.`;
    }
    return `${keyword}와 관련된 용도로 사용하려는 공간에서 활용할 수 있는지 살펴보면 좋습니다. 평소 제품을 사용할 장소와 필요한 목적을 먼저 생각해보면 선택하기 편합니다.`;
  })();

  const recommendedUse = (() => {
    if (features.includes("유튜브 촬영") || features.includes("수직 촬영")) {
      return `유튜브 영상이나 세로형 콘텐츠처럼 촬영 목적이 뚜렷한 경우 먼저 살펴보기 좋습니다. 핸드폰을 활용한 촬영 환경을 만들려는 경우에도 상품명에 표시된 거치와 촬영 관련 특징을 기준으로 비교해볼 수 있습니다.`;
    }
    if (features.includes("캠핑 활용") || features.includes("등산 활용") || features.includes("러닝 활용") || features.includes("마라톤 활용")) {
      return `캠핑, 등산, 러닝, 마라톤처럼 상품명에 표시된 야외활동과 관련된 상황에서 활용처를 생각해볼 수 있습니다. 실제 사용 목적에 필요한 구성인지 확인한 뒤 선택하면 좋습니다.`;
    }
    if (features.includes("청소기 형태")) {
      return `일상적인 집안 청소를 위해 사용할 제품을 찾을 때 비교해볼 수 있습니다. 헤드브러시나 침구 브러시처럼 상품명에 표시된 구성도 함께 살펴보면서 내가 필요한 청소 환경과 맞는지 확인해보세요.`;
    }
    return `${keyword}와 관련된 제품이 필요한 상황에서 활용처를 생각해볼 수 있습니다. 내가 자주 사용할 장소와 목적을 먼저 정한 뒤 상품명에 표시된 특징과 비교해보세요.`;
  })();

  const body = [
    "인사말",
    `안녕하세요. 오늘은 ${keyword}와 관련해 살펴볼 만한 ${productName}을 소개해드릴게요. 복잡한 내용보다는 제품의 특징과 어떤 상황에서 활용하기 좋은지를 중심으로 편하게 정리해보겠습니다.`,
    "제품소개",
    intro,
    "추천이유",
    reason,
    "장점",
    advantages,
    "단점",
    disadvantages,
    "어디에 사용하면 좋은지",
    goodPlace,
    "추천사용처",
    recommendedUse,
    "파트너스 링크",
    "관심이 있다면 아래 상품 확인하기 버튼에서 자세한 상품 정보를 확인해보세요.",
    "마무리 인사",
    `오늘은 ${productName}의 상품명에서 확인되는 특징과 활용하기 좋은 상황을 중심으로 살펴봤습니다. 필요한 용도와 잘 맞는지 비교해보시고, 더 자세한 구성과 기능은 상품 상세 페이지에서 확인해보시면 좋겠습니다. 읽어주셔서 감사합니다.`,
  ].join("\n\n");

  return { titles, selectedTitle: titles[0], body, disclosure: DISCLOSURE };
}
