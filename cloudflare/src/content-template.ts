const DISCLOSURE = "이 포스팅은 쿠팡 파트너스 활동의 일환으로, 이에 따른 일정액의 수수료를 제공받습니다.";

/**
 * 쿠팡 상품명을 바탕으로 네이버 블로그용 글을 작성합니다.
 *
 * 글의 핵심은 상품 자체를 설명하는 것입니다.
 * 제목 → 고지문 → 인사말 → 제품소개 → 추천이유 → 장점 → 단점
 * → 사용하기 좋은 곳 → 추천 사용처 → 상품 확인 안내 → 마무리 순서로 구성합니다.
 * 가격, 배송, 검색순위 등은 본문에 넣지 않습니다.
 * 상품명에 없는 성능이나 스펙은 임의로 만들지 않습니다.
 */
export function buildProductPost(keyword: string, productName: string, _researchEvidence: string[] = []) {
  // 상품명에서 실제로 확인되는 특징만 골라냅니다.
  const rules: Array<[RegExp, string, string]> = [
    [/무선/, "무선", "무선 방식의 제품으로 표시되어 있습니다."],
    [/청소기/, "청소", "청소 용도로 사용할 수 있는 제품으로 표시되어 있습니다."],
    [/헤드브러시/, "헤드브러시", "헤드브러시가 상품명에 표시되어 있습니다."],
    [/침구브러시/, "침구 브러시", "침구 브러시가 상품명에 표시되어 있습니다."],
    [/필터/, "필터", "필터가 상품명에 표시되어 있습니다."],
    [/LED/, "LED 조명", "LED 조명이 상품명에 표시되어 있습니다."],
    [/링라이트/, "링라이트", "링라이트가 상품명에 표시되어 있습니다."],
    [/조명/, "조명", "조명 제품으로 표시되어 있습니다."],
    [/촬영/, "촬영", "촬영 용도가 상품명에 표시되어 있습니다."],
    [/핸드폰|스마트폰/, "핸드폰 촬영", "핸드폰 촬영과 관련된 특징이 상품명에 표시되어 있습니다."],
    [/거치대|거치/, "거치", "기기를 거치해 사용하는 특징이 상품명에 표시되어 있습니다."],
    [/높이조절|높이/, "높이 조절", "높이 조절 기능이 상품명에 표시되어 있습니다."],
    [/수직촬영/, "수직 촬영", "수직 촬영 용도가 상품명에 표시되어 있습니다."],
    [/유튜브/, "유튜브 촬영", "유튜브 촬영과 관련된 용도가 상품명에 표시되어 있습니다."],
    [/캠핑/, "캠핑", "캠핑 관련 활용처가 상품명에 표시되어 있습니다."],
    [/보온/, "보온", "보온 용도가 상품명에 표시되어 있습니다."],
    [/방한/, "방한", "방한 용도가 상품명에 표시되어 있습니다."],
    [/등산/, "등산", "등산 관련 활용처가 상품명에 표시되어 있습니다."],
    [/러닝/, "러닝", "러닝 관련 활용처가 상품명에 표시되어 있습니다."],
    [/마라톤/, "마라톤", "마라톤 관련 활용처가 상품명에 표시되어 있습니다."],
    [/차량용/, "차량용", "차량에서 사용하는 용도로 표시되어 있습니다."],
    [/주방/, "주방용", "주방에서 사용하는 용도로 표시되어 있습니다."],
    [/수납/, "수납", "수납 용도로 사용할 수 있는 제품으로 표시되어 있습니다."],
    [/이어폰/, "이어폰", "이어폰 제품으로 표시되어 있습니다."],
    [/공기청정기/, "공기청정", "공기청정 용도의 제품으로 표시되어 있습니다."],
    [/키보드/, "키보드", "키보드 제품으로 표시되어 있습니다."],
    [/마우스/, "마우스", "마우스 제품으로 표시되어 있습니다."],
    [/거울/, "거울", "거울 제품으로 표시되어 있습니다."],
    [/선풍기/, "선풍", "선풍 용도의 제품으로 표시되어 있습니다."],
    [/가습기/, "가습", "가습 용도의 제품으로 표시되어 있습니다."],
    [/텀블러|보온병/, "보온용기", "보온용기로 사용할 수 있는 제품으로 표시되어 있습니다."],
  ];

  const matched = rules.filter(([pattern]) => pattern.test(productName));
  const features = [...new Set(matched.map(([, label]) => label))];
  const descriptions = [...new Set(matched.map(([, , description]) => description))];
  const featureText = features.length ? features.join(", ") : "상품명에 표시된 특징";

  // 상품의 특징을 설명하는 문장을 자연스럽게 구성합니다.
  const introduction = descriptions.length
    ? `${productName}은 ${featureText}와 같은 내용이 상품명에 표시된 제품입니다. ${descriptions.slice(0, 5).join(" ")} 상품명에서 확인할 수 있는 범위 안에서 보면 ${featureText}을 중심으로 살펴볼 수 있습니다.`
    : `${productName}은 ${keyword}와 관련해 살펴볼 수 있는 제품입니다. 현재 확인되는 상품명과 표시된 용도를 중심으로 소개해보겠습니다.`;

  const recommendation = features.length
    ? `${featureText}처럼 사용 목적과 연결되는 특징이 상품명에 분명하게 표시되어 있습니다. ${keyword}와 관련된 제품을 찾으면서 이런 용도가 필요한 분이라면 비교 목록에 넣어 살펴보기 좋습니다.`
    : `${keyword}와 관련된 제품을 찾고 있다면 상품명에 표시된 용도와 본인이 필요한 사용 목적이 맞는지 비교해보는 방식으로 살펴볼 수 있습니다.`;

  // 장점은 상품명에서 확인 가능한 특징을 중심으로만 작성합니다.
  const advantages = features.length
    ? `${featureText}처럼 상품의 주요 용도와 특징을 상품명에서 바로 확인할 수 있다는 점이 장점입니다. 원하는 사용 목적이 분명하다면 비슷한 제품을 비교할 때 필요한 기준을 잡기 편합니다.`
    : `상품명에서 제품의 용도와 이름을 바로 확인할 수 있어 비슷한 상품과 비교할 때 기준을 잡기 편합니다.`;

  // 실제 사용 후기를 가장하지 않고, 확인되지 않은 단점을 만들어내지 않습니다.
  const disadvantages = features.length
    ? `상품명만으로는 ${featureText}에 대한 세부적인 성능이나 구성까지 알 수 없다는 점은 아쉬울 수 있습니다. 필요한 세부 내용은 상품 상세 페이지에서 확인하는 것이 좋습니다.`
    : `상품명만으로 세부적인 기능과 구성을 모두 확인하기 어렵다는 점은 아쉬운 부분입니다.`;

  // 상품명에 들어 있는 용도를 기준으로 사용하기 좋은 장소를 정합니다.
  const goodPlace = (() => {
    if (features.some((x) => /촬영|링라이트|핸드폰 촬영|거치|높이 조절|수직 촬영|유튜브/.test(x))) {
      return "책상이나 촬영 공간처럼 조명이나 촬영 장비를 두고 사용하는 곳에서 활용하기 좋습니다.";
    }
    if (features.some((x) => /청소|헤드브러시|침구 브러시|필터/.test(x))) {
      return "집 안에서 청소가 필요한 공간을 중심으로 활용하기 좋습니다. 평소 청소하려는 공간과 제품에 표시된 용도를 함께 살펴보면 됩니다.";
    }
    if (features.some((x) => /캠핑|보온|방한|등산|러닝|마라톤/.test(x))) {
      return "상품명에 표시된 야외활동이나 계절 관련 용도가 필요한 상황에서 활용하기 좋습니다.";
    }
    if (features.includes("차량용")) {
      return "차량 안에서 해당 용도의 제품이 필요한 경우 활용하기 좋습니다.";
    }
    if (features.some((x) => /주방용|수납|보온용기|가습|선풍/.test(x))) {
      return "집이나 생활 공간에서 해당 용도의 제품이 필요한 곳에 활용하기 좋습니다.";
    }
    return `${keyword}와 관련된 제품이 필요한 생활 공간이나 작업 공간에서 활용할 수 있습니다.`;
  })();

  const recommendedUse = (() => {
    if (features.some((x) => /유튜브 촬영|수직 촬영|촬영|링라이트/.test(x))) {
      return "유튜브나 세로형 영상처럼 촬영이 필요한 경우 추천 사용처로 생각해볼 수 있습니다. 핸드폰 촬영이 필요하다면 거치와 조명 관련 특징을 함께 살펴보세요.";
    }
    if (features.some((x) => /청소|헤드브러시|침구 브러시/.test(x))) {
      return "집안 청소가 필요한 공간에서 사용하기 좋습니다. 상품명에 표시된 브러시나 필터 관련 특징이 본인의 청소 목적과 맞는지도 함께 확인해보세요.";
    }
    if (features.some((x) => /캠핑|등산|러닝|마라톤/.test(x))) {
      return "캠핑, 등산, 러닝, 마라톤처럼 상품명에 표시된 활동을 준비할 때 추천 사용처로 생각해볼 수 있습니다.";
    }
    if (features.includes("차량용")) {
      return "차량 안에서 필요한 용도로 사용하는 경우를 추천 사용처로 생각해볼 수 있습니다.";
    }
    return `${keyword}와 관련해 제품이 필요한 상황에서 활용할 수 있습니다. 본인이 실제로 사용할 장소와 목적에 맞춰 살펴보면 좋습니다.`;
  })();

  // 제목은 5개를 만들되 비슷한 문장을 반복하지 않습니다.
  const titles = [
    `${productName} 특징과 활용법 알아보기`,
    `${productName} 제품 소개와 추천 사용처`,
    `${productName} 어떤 곳에서 사용하면 좋을까`,
    `${productName} 장점과 활용 포인트 정리`,
    `${keyword} 찾는다면 살펴볼 ${productName}`,
  ];

  // 실제 블로그 본문에는 항목 이름을 그대로 노출하지 않고 자연스러운 소제목으로 구성합니다.
  const body = [
    `안녕하세요. 오늘은 ${keyword}를 찾다가 살펴보게 된 ${productName}을 소개해드릴게요. 상품명에서 확인되는 특징과 어떤 상황에서 활용하기 좋은지 중심으로 편하게 정리해보겠습니다.`,
    `### 제품 소개\n${introduction}`,
    `### 이런 분께 추천해요\n${recommendation}`,
    `### 장점\n${advantages}`,
    `### 단점\n${disadvantages}`,
    `### 어디에 사용하면 좋을까요?\n${goodPlace}`,
    `### 추천 사용처\n${recommendedUse}`,
    `### 상품 확인\n관심이 있다면 아래 상품 확인하기 버튼을 통해 현재 판매 페이지의 상품 정보를 직접 확인해보세요.`,
    `오늘은 ${productName}의 특징과 활용 방법을 중심으로 살펴봤습니다. 본인에게 필요한 용도와 잘 맞는지 비교해보시고, 세부적인 기능이나 구성은 상품 상세 페이지에서 확인해보시면 좋겠습니다. 읽어주셔서 감사합니다.`,
  ].join("\n\n");

  return { titles, selectedTitle: titles[0], body, disclosure: DISCLOSURE };
}
